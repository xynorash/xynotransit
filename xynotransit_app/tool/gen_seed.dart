// Writes ../xynotransit-db/examples/10-seed.sql (catalog) and 20-seed-demo.sql (14 demo reports)
// from the same data the app uses. Run: dart run tool/gen_seed.dart
import 'dart:io';

import 'package:xynotransit_app/data/demo_data.dart';
import 'package:xynotransit_app/data/seed_data.dart';
import 'package:xynotransit_app/domain/enums.dart';

String q(String s) => "'${s.replaceAll("'", "''")}'";

String email(String person) => '${person.toLowerCase()}@xynotransit.example';

void main() {
  final catalog = buildSeedCatalog();
  final out = StringBuffer()
    ..writeln('-- Xynotransit Logistics Report Builder: catalog seed.')
    ..writeln(
      '-- Generated by tool/gen_seed.dart from lib/data/seed_data.dart. Do not edit by hand.',
    )
    ..writeln(
      '-- Example data, not loaded automatically: a fresh database starts with an empty catalog.',
    )
    ..writeln(
      '-- Load it by hand with psql after the schema, if you want to try the app with people in it.',
    )
    ..writeln(
      '-- Emails are placeholders: replace them with the real ones before people sign in.',
    )
    ..writeln(
      '-- Set BOOTSTRAP_CONTROLLER_EMAIL on the API to make one person the controller.',
    )
    ..writeln()
    ..writeln('begin;')
    ..writeln();

  out.writeln('insert into team (code, name, sort) values');
  out.writeln(
    seedTeams.indexed
        .map((e) => '  (${q(e.$2.$1)}, ${q(e.$2.$2)}, ${e.$1 + 1})')
        .join(',\n'),
  );
  out.writeln(';\n');

  final people = <String>[];
  for (final a in seedAssignments) {
    if (!people.contains(a.person)) people.add(a.person);
  }
  out.writeln('insert into person (full_name, email) values');
  out.writeln(people.map((p) => '  (${q(p)}, ${q(email(p))})').join(',\n'));
  out.writeln(';\n');

  final sortInTeam = <String, int>{};
  for (final a in seedAssignments) {
    final sort = (sortInTeam[a.team] ?? 0) + 1;
    sortInTeam[a.team] = sort;
    out.writeln(
      'insert into assignment (code, person_id, team_id, role_title, sort)',
    );
    out.writeln('select ${q(a.code)}, p.id, t.id, ${q(a.role)}, $sort');
    out.writeln(
      'from person p, team t where p.email = ${q(email(a.person))} and t.code = ${q(a.team)};',
    );
    for (final (i, m) in a.metrics.indexed) {
      out.writeln('insert into metric_def (assignment_id, key, label, series)');
      out.writeln(
        'select a.id, ${q(m.$1)}, ${q(m.$2)}, $i from assignment a where a.code = ${q(a.code)};',
      );
    }
    for (final (i, k) in a.kpis.indexed) {
      out.writeln('insert into kpi_def (assignment_id, sort, text)');
      out.writeln(
        'select a.id, ${i + 1}, ${q(k)} from assignment a where a.code = ${q(a.code)};',
      );
    }
    out.writeln();
  }

  out.writeln('commit;');
  File('../xynotransit-db/examples/10-seed.sql')
      .writeAsStringSync(out.toString());

  // Demo reports for Feb to Apr 2026.
  final demo = StringBuffer()
    ..writeln(
      '-- Xynotransit Logistics Report Builder: DEMO reports for Feb to Apr 2026.',
    )
    ..writeln(
      '-- Generated by tool/gen_seed.dart. Demo data only: not loaded automatically, load it by hand after examples/10-seed.sql.',
    )
    ..writeln()
    ..writeln('begin;')
    ..writeln()
    ..writeln(
      "insert into period (start_month, meeting_date) values ('2026-02-01', '2026-06-09')",
    )
    ..writeln(
      'on conflict (start_month) do update set meeting_date = excluded.meeting_date;',
    )
    ..writeln();
  final reports = buildDemoReports(catalog, 'demo');
  for (final r in reports) {
    final code = r.assignmentId;
    final at = r.submittedAt!.toIso8601String();
    demo
      ..writeln('-- $code')
      ..writeln(
        'insert into report (period_id, assignment_id, status, submitted_at)',
      )
      ..writeln("select p.id, a.id, 'submitted', ${q(at)}")
      ..writeln(
        "from period p, assignment a where p.start_month = '2026-02-01' and a.code = ${q(code)};",
      );
    String where(String table) => '''
from report r
join period p on p.id = r.period_id and p.start_month = '2026-02-01'
join assignment a on a.id = r.assignment_id and a.code = ${q(code)}''';
    for (final e in r.values.entries) {
      final key = e.key.split('/').last;
      for (var m = 0; m < 3; m++) {
        demo
          ..writeln(
            'insert into report_metric_value (report_id, assignment_id, metric_def_id, month_offset, value)',
          )
          ..writeln('select r.id, a.id, md.id, $m, ${e.value[m]}')
          ..writeln(
            '${where('r')}\njoin metric_def md on md.assignment_id = a.id and md.key = ${q(key)};',
          );
      }
    }
    for (final e in r.kpis.entries) {
      final sort = int.parse(e.key.split('/k').last);
      demo
        ..writeln(
          'insert into report_kpi_result (report_id, assignment_id, kpi_def_id, status, comment)',
        )
        ..writeln(
          'select r.id, a.id, k.id, ${q(e.value.status.name)}, ${e.value.comment == null ? 'null' : q(e.value.comment!)}',
        )
        ..writeln(
          '${where('r')}\njoin kpi_def k on k.assignment_id = a.id and k.sort = $sort;',
        );
    }
    for (final kind in NoteKind.values) {
      for (final (i, text) in r.notesOf(kind).indexed) {
        demo
          ..writeln('insert into report_note (report_id, kind, position, text)')
          ..writeln('select r.id, ${q(kind.name)}, ${i + 1}, ${q(text)}')
          ..writeln('${where('r')};');
      }
    }
    demo.writeln();
  }
  demo.writeln('commit;');
  File('../xynotransit-db/examples/20-seed-demo.sql')
      .writeAsStringSync(demo.toString());
  stdout.writeln(
    'Wrote ../xynotransit-db/examples/10-seed.sql and 20-seed-demo.sql',
  );
}
